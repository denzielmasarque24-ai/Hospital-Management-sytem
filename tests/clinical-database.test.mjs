import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
let PGlite;
try { ({ PGlite } = await import('../.tmp/clinical-db/node_modules/@electric-sql/pglite/dist/index.js')); } catch {}
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;

test('clinical migration enforces clinical grants, workflow locks, private storage, patient isolation and atomic notifications', { skip: !PGlite && 'Install the local PGlite engine as described in docs/clinical-records.md' }, async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon; create role authenticated; create schema auth; create schema storage;
      create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      grant usage on schema public,auth,storage to authenticated,anon;
      create table public.profiles(id uuid primary key references auth.users(id),role text,first_name text,middle_name text,last_name text,suffix text);
      create table public.doctors(id uuid primary key,display_name text,specialty text,is_demo boolean);
      create table public.lab_tests(id uuid primary key,name text);
      create table public.lab_test_bookings(id uuid primary key,patient_id uuid references public.profiles(id),lab_test_id uuid references public.lab_tests(id),booking_date date,booking_time time,status text);
      create table public.patient_medical_records(id uuid primary key default gen_random_uuid(),patient_id uuid references public.profiles(id),doctor_id uuid references public.doctors(id),record_type text not null,title text,description text,record_date date,result_status text,is_demo boolean,demo_key text,created_at timestamptz default now());
      create table public.patient_notifications(id uuid primary key default gen_random_uuid(),patient_id uuid,title text,body text,event_key text,unique(patient_id,event_key));
      create table public.test_permissions(user_id uuid,permission text);
      create function public.can_manage_patient_area(p_area text) returns boolean language sql stable security definer set search_path='' as $$select exists(select 1 from public.test_permissions where user_id=auth.uid() and permission=p_area)$$;
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text);
      alter table storage.objects enable row level security;
      grant select,insert,update,delete on storage.objects to authenticated;
      insert into auth.users values ${[1,2,3,4,5].map(n=>`('${id(n)}')`).join(',')};
      insert into public.profiles(id,role,first_name,last_name) values ('${id(1)}','PATIENT','Patient','One'),('${id(2)}','PATIENT','Patient','Two'),('${id(3)}','CLINICIAN','Author','Staff'),('${id(4)}','CLINICIAN','Review','Staff'),('${id(5)}','ADMIN','General','Admin');
      insert into public.test_permissions values ('${id(3)}','clinical_author'),('${id(3)}','lab_author'),('${id(4)}','clinical_release'),('${id(4)}','lab_release');
      insert into public.doctors values ('${id(10)}','Fixture Doctor','Medicine',false);
      insert into public.lab_tests values ('${id(11)}','Fixture Lab Test');
      insert into public.lab_test_bookings values ('${id(12)}','${id(1)}','${id(11)}','2026-10-24','08:00','completed');
      insert into public.patient_medical_records(id,patient_id,record_type,title,result_status,is_demo) values ('${id(90)}','${id(1)}','consultation','Historical demo','recorded',true);
    `);
    await db.exec(readFileSync(new URL('../supabase/migrations/20261217000000_clinical_record_delivery.sql',import.meta.url),'utf8'));
    const asUser = async n => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id(n)]); await db.exec('set role authenticated'); };
    const rpc = async (name,args) => (await db.query(`select public.${name}(${args.map((_,index)=>'$'+(index+1)).join(',')}) result`,args)).rows[0].result;
    const values = {title:'Private fixture',description:'Confidential findings',date:'2026-10-24',doctor_id:id(10),record_type:'consultation',test_id:id(11),booking_id:id(12)};
    await asUser(5);
    await assert.rejects(()=>rpc('clinical_workspace',['medical','','',0]),/uuid|permission/i);
    await assert.rejects(()=>rpc('clinical_workspace',['medical','',null,0]),/permission/i);
    await assert.rejects(()=>rpc('clinical_save_record',['medical',id(20),id(1),values,null]),/permission/i);
    await asUser(3);
    let medical=await rpc('clinical_save_record',['medical',id(20),id(1),values,null]);
    assert.equal(medical.delivery_state,'draft');
    await assert.rejects(()=>rpc('clinical_transition_record',['medical',id(20),id(1),'review',medical.updated_at]),/permission/i);
    await assert.rejects(()=>rpc('clinical_save_record',['lab',id(21),id(2),values,null]),/Booking must belong/);
    await asUser(4);
    await assert.rejects(()=>rpc('clinical_transition_record',['medical',id(20),id(1),'release',medical.updated_at]),/review is required/i);
    await asUser(1);
    assert.equal((await db.query('select * from public.patient_medical_records where id=$1',[id(20)])).rows.length,0);
    assert.equal((await db.query('select title,is_demo from public.patient_medical_records where id=$1',[id(90)])).rows[0].title,'Historical demo');
    await asUser(3);
    // The storage object is inserted by the upload server only, after validation.
    await db.exec('reset role');
    const path=`${id(1)}/medical/${id(20)}/${id(30)}.pdf`;
    await db.query("insert into storage.objects(bucket_id,name) values ('patient-medical-documents',$1)",[path]);
    await asUser(3);
    await rpc('clinical_attach_document',['medical',id(20),id(1),id(30),path,'report.pdf','application/pdf',128]);
    await assert.rejects(()=>db.query("insert into storage.objects(bucket_id,name) values ('patient-medical-documents','bad.pdf')"),/row-level security/i);
    medical=(await db.query('select * from public.patient_medical_records where id=$1',[id(20)])).rows[0];
    await asUser(1);
    await assert.rejects(()=>rpc('clinical_document_access',[id(30)]),/unavailable/i);
    assert.equal((await db.query('select * from storage.objects')).rows.length,0);
    await asUser(4);
    medical=await rpc('clinical_transition_record',['medical',id(20),id(1),'review',medical.updated_at]);
    assert.equal(medical.delivery_state,'reviewed');
    await db.exec('reset role');
    await assert.rejects(()=>db.query('update public.patient_medical_records set description=$1 where id=$2',['Changed after review',id(20)]),/Return to draft/);
    await asUser(3);
    await assert.rejects(()=>rpc('clinical_save_record',['medical',id(20),id(1),values,medical.updated_at]),/Only genuine drafts/);
    await asUser(4);
    medical=await rpc('clinical_transition_record',['medical',id(20),id(1),'release',medical.updated_at]);
    assert.equal(medical.delivery_state,'released');
    await assert.rejects(()=>rpc('clinical_transition_record',['medical',id(20),id(1),'release',medical.updated_at]),/review is required/);
    await asUser(2);
    assert.equal((await db.query('select * from public.patient_medical_records where id=$1',[id(20)])).rows.length,0);
    assert.equal((await db.query('select * from public.patient_clinical_documents')).rows.length,0);
    await assert.rejects(()=>rpc('clinical_document_access',[id(30)]),/unavailable/);
    await asUser(1);
    assert.equal((await db.query('select * from public.patient_medical_records where id=$1',[id(20)])).rows.length,1);
    assert.equal((await rpc('clinical_document_access',[id(30)])).object_path,path);
    assert.equal((await db.query('select * from storage.objects')).rows.length,1);
    await asUser(3);
    let lab=await rpc('clinical_save_record',['lab',id(21),id(1),values,null]);
    await assert.rejects(()=>rpc('clinical_save_record',['lab',id(21),id(2),values,lab.updated_at]),/ownership mismatch/);
    await assert.rejects(()=>rpc('clinical_save_record',['lab',id(21),id(1),values,null]),/Record changed/);
    await asUser(4);
    await assert.rejects(()=>rpc('clinical_transition_record',['lab',id(21),id(2),'review',lab.updated_at]),/not found/);
    lab=await rpc('clinical_transition_record',['lab',id(21),id(1),'review',lab.updated_at]);
    lab=await rpc('clinical_transition_record',['lab',id(21),id(1),'return_to_draft',lab.updated_at]);
    assert.equal(lab.reviewed_at,null);
    lab=await rpc('clinical_transition_record',['lab',id(21),id(1),'review',lab.updated_at]);
    lab=await rpc('clinical_transition_record',['lab',id(21),id(1),'release',lab.updated_at]);
    await asUser(2);
    assert.equal((await db.query('select * from public.patient_lab_results')).rows.length,0);
    await asUser(1);
    assert.equal((await db.query('select * from public.patient_lab_results')).rows.length,1);
    await db.exec('reset role');
    const notices=(await db.query('select * from public.patient_notifications order by event_key')).rows;
    assert.equal(notices.length,2); assert.ok(notices.every(row=>row.patient_id===id(1)));
    assert.ok(notices.every(row=>!row.body.includes('Confidential')&&!row.title.includes('Private fixture')));
    assert.deepEqual(new Set(notices.map(row=>row.href)),new Set(['/patient/medical-history','/patient/laboratory-results']));
    assert.equal((await db.query('select * from storage.buckets')).rows[0].public,false);
    assert.equal((await db.query('select * from public.patient_medical_records where id=$1',[id(90)])).rows[0].title,'Historical demo');
    assert.ok((await db.query("select * from public.patient_clinical_events where action='release'")).rows.length===2);
  } finally { await db.close(); }
});
